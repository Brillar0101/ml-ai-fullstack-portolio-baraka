/**
 * Writes public/gemoji/config.js from the environment.
 *
 * The game at /gemoji is a plain static file, so Vite never processes it and
 * `import.meta.env` is not available inside it. This bridges the gap: it emits
 * a tiny script that sets window.GEMOJI_CONFIG, which the game reads to decide
 * whether shared online games are possible.
 *
 * The output is gitignored. It carries only the Supabase URL and the anon key,
 * which are public by design and already shipped in the React bundle. Nothing
 * secret belongs in here: never write a service-role key to this file.
 *
 * Missing credentials are NOT an error. The game falls back to on-device play,
 * so a contributor without a .env.local still gets a working build.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, '..', 'public', 'gemoji', 'config.js');

const url = process.env.VITE_SUPABASE_URL ?? '';
const key = process.env.VITE_SUPABASE_ANON_KEY ?? '';

// A service-role key here would be handed to every visitor. Refuse outright.
if (key.includes('service_role') || process.env.SUPABASE_SERVICE_ROLE_KEY === key && key) {
  console.error('[gemoji] Refusing to write a service-role key into a public file.');
  process.exit(1);
}

const banner = '/* Generated by scripts/gen-gemoji-config.mjs. Do not edit or commit. */\n';

let body;
if (url && key) {
  body = `window.GEMOJI_CONFIG = ${JSON.stringify({ supabaseUrl: url, supabaseAnonKey: key })};\n`;
  console.log('[gemoji] config written, shared online games enabled');
} else {
  body = 'window.GEMOJI_CONFIG = null; /* no Supabase credentials at build time */\n';
  const missing = [!url && 'VITE_SUPABASE_URL', !key && 'VITE_SUPABASE_ANON_KEY'].filter(Boolean);
  console.log(`[gemoji] ${missing.join(' and ')} not set, so the game will run on-device only`);
}

await mkdir(dirname(target), { recursive: true });
await writeFile(target, banner + body, 'utf8');
